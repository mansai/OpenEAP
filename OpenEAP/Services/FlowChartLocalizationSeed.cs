        /// <summary>将流程图设计器文案写入指定数据库，可在维护工具中复用。</summary>
        public static void Apply(IFreeSql db)
        {
            var keys = Entries.Select(e => e.Key).Distinct().ToList();
            var existing = db.Select<ResourcesEntity>()
                .Where(t => keys.Contains(t.Key))
                .ToList()
                .GroupBy(t => $"{t.Key}|{t.Culture}")
                .ToDictionary(g => g.Key, g => g.First());

            foreach (var e in Entries)
            {
                EnsureOne(db, existing, e.Key, "zh-Hans", e.ZhHans);
                EnsureOne(db, existing, e.Key, "en-US", e.EnUs);
            }
        }

        private static void EnsureOne(IFreeSql db, Dictionary<string, ResourcesEntity> existing,
            string key, string culture, string value)
        {
            var lookup = $"{key}|{culture}";
            if (existing.TryGetValue(lookup, out var current))
            {
                if (string.IsNullOrWhiteSpace(current.Value) || current.Value == current.Key)
                {
                    current.Value = value;
                    db.Update<ResourcesEntity>()
                        .Set(t => t.Value, value)
                        .Where(t => t.Id == current.Id)
                        .ExecuteAffrows();
                }
                return;
            }

            var entity = new ResourcesEntity
            {
                ModuleId = 0,
                Culture = culture,
                Key = key,
                Value = value,
                Type = "99",
                IsDeleted = "N",
            };
            db.Insert(entity).ExecuteAffrows();
            existing[lookup] = entity;
        }
